export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6; // 5 + 1px 字距

function expand(raw) {
  return raw.split('/').map((r) => r.replace(/1/g, '#').replace(/0/g, '.'));
}

export const GLYPHS = Object.fromEntries(Object.entries(RAW).map(([k, v]) => [k, expand(v)]));

export function glyphFor(ch) {
  const up = String(ch).toUpperCase();
  return GLYPHS[up] || GLYPHS[' '];
}

export function isSupported(ch) {
  return Object.hasOwn(GLYPHS, String(ch).toUpperCase());
}

export function textWidth(text, scale = 1) {
  return String(text).length * ADVANCE * scale;
}

/**
 * 画点阵文字（只在浏览器里调用）。
 * @param {CanvasRenderingContext2D} ctx
 */
export function drawText(ctx, text, x, y, color = '#cfd8e6', scale = 1, shadow = null) {
  const s = String(text).toUpperCase();
  if (shadow) {
    ctx.fillStyle = shadow;
    for (let i = 0; i < s.length; i++) paint(ctx, s[i], x + i * ADVANCE * scale + scale, y + scale, scale, 1);
  }
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) paint(ctx, s[i], x + i * ADVANCE * scale, y, scale, 0);
}

function paint(ctx, ch, x, y, scale, dy) {
  const rows = glyphFor(ch);
  for (let r = 0; r < GLYPH_H; r++) {
    const row = rows[r];
    let runStart = -1;
    for (let c = 0; c <= GLYPH_W; c++) {
      const on = c < GLYPH_W && row[c] === '#';
      if (on && runStart < 0) runStart = c;
      if (!on && runStart >= 0) {
        ctx.fillRect(x + runStart * scale, y + r * scale + dy, (c - runStart) * scale, scale);
        runStart = -1;
      }
    }
  }
}
